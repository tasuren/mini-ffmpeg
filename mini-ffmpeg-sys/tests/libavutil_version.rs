//! Call cinrs-translated `libavutil/version.c` from Rust to verify it.
//!
//! These are integration tests to ensure linking succeeds. `cargo build` alone
//! does not link a library crate and can succeed despite unresolved symbols.

use std::ffi::CStr;

use mini_ffmpeg_sys::libavutil::version;

/// Read `version` from the build manifest's `[ffmpeg]` section.
///
/// Hard-coding the expected value would require updates whenever FFmpeg is updated.
/// Compare against the value the tool read from the same build instead.
///
/// Build manifest locations vary by target, so use the path supplied by the build
/// script through `rustc-env`.
fn manifest_ffmpeg_version() -> &'static str {
    include_str!(env!("MINI_FFMPEG_SYS_MANIFEST"))
        .lines()
        .find_map(|line| line.strip_prefix("version = "))
        .expect("build manifest contains version")
        .trim_matches('"')
}

/// `FFMPEG_VERSION` is in `libavutil/ffversion.h`, generated by `make`.
/// Returning this value verifies that translation read `FFmpeg_build/<target>` as
/// an include directory and that Rust can call the C function.
#[test]
fn av_version_info_returns_ffversion_h_value() {
    let version = unsafe { CStr::from_ptr(version::av_version_info()) };

    assert_eq!(version.to_str().unwrap(), manifest_ffmpeg_version());
}

/// `FFMPEG_LICENSE` is in `config.h`, generated by `configure`. GPL components are
/// excluded by policy, so also verify that the recorded configuration is LGPL.
///
/// The C function returns a pointer into the concatenated string literal
/// `"libavutil license: " FFMPEG_LICENSE`.
#[test]
fn avutil_license_returns_config_h_value() {
    let license = unsafe { CStr::from_ptr(version::avutil_license()) };

    assert_eq!(license.to_str().unwrap(), "LGPL version 2.1 or later");
}

/// `LIBAVUTIL_VERSION_INT` is `major << 16 | minor << 8 | micro`, with micro starting
/// at 100. Values vary with the FFmpeg version, so check only the layout. This
/// verifies that headers in the FFmpeg source tree (`libavutil/version.h`) were read.
#[test]
fn avutil_version_has_expected_layout() {
    let version = unsafe { version::avutil_version() };

    assert!(version >> 16 > 0, "major: {version:#x}");
    assert!(version & 0xff >= 100, "micro: {version:#x}");
}
