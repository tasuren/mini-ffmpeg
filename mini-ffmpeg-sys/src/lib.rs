//! FFmpeg's libav\* libraries translated to Rust with cinrs.
//!
//! FFmpeg's public API (function declarations, structs, and enumerators) is exposed
//! at the crate root under the original C names, such as
//! `mini_ffmpeg_sys::avformat_open_input`. It is translated from FFmpeg's public
//! headers (`public_headers` in the build manifest) and contains only declarations
//! for functions.
//!
//! Function definitions reside in implementation translation units, translated
//! from individual FFmpeg `.c` files. They are grouped under library modules:
//! `libavutil/time.c` becomes `libavutil::time`. These are not intended for users
//! and are hidden from documentation (`#[doc(hidden)]`). Public API declarations
//! link to these definitions by C symbol names.
//!
//! This crate's build script (`build.rs`) performs translation. It writes translated
//! code to Cargo's output directory, where this file loads it with `include!`.
//! See `build/translate.rs` for translation settings and `build.rs` for why
//! translation happens in the build script.
//!
//! Implementation translation units also refer to each other by C symbol names,
//! rather than Rust module paths. Types such as structs therefore become distinct
//! Rust types in each translation unit, even when multiple units read the same
//! header. Each module contains only definitions from that unit and the items they
//! use. The public API is one translation unit, so its types are shared and it
//! contains all public header declarations and types.
//!
//! The public API also contains declarations (such as `strcat`) from platform
//! headers included by public headers.
//!
//! Besides Rust code, the crate directory contains the following translation
//! inputs read by the build script:
//!
//! - `FFmpeg/`: FFmpeg source tree, a Git submodule.
//! - `FFmpeg_build/<target-triple>/`: Target-specific build configurations.
//!   - `cinrs_manifest.toml`: Build manifest recording information read from an FFmpeg build.
//!   - Other files: Files generated by FFmpeg's `configure` and `make`.
//!
//! `FFmpeg_build/` is generated by `cargo xtask ffmpeg-manifest`; do not edit it manually.

// Module declarations emitted by the build script: the public API module and its
// re-export (`pub use public_api::*;`), followed by implementation translation unit
// modules grouped by library, such as `pub mod libavutil { … }`.
include!(concat!(env!("OUT_DIR"), "/generated.rs"));
