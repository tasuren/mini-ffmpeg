//! Development task commands for mini-ffmpeg.
//!
//! Run with `cargo xtask <task>` (the alias in `.cargo/config.toml`).
//!
//! These tasks are for maintainers during development and do not run in consumer builds.
//! Keeping work that requires FFmpeg's `configure` or `make` here and committing the
//! results allows normal builds to use Cargo alone.

mod ffmpeg_license;
mod ffmpeg_manifest;

use std::{
    env,
    path::{Path, PathBuf},
    process::ExitCode,
};

/// The `Result` type shared by all tasks.
///
/// These development commands only print errors and exit, so errors are handled as
/// strings rather than separate error types.
type Result<T> = std::result::Result<T, Box<dyn std::error::Error>>;

/// Directory for target-specific build configurations, relative to `mini-ffmpeg-sys`.
///
/// Each configuration lives in `FFmpeg_build/<target-triple>/` and contains the build
/// manifest ([`MANIFEST_FILE`]) and files generated by `configure` and `make`.
/// `ffmpeg-manifest` writes them, and `mini-ffmpeg-sys`'s `build.rs` reads them.
const BUILD_CONFIG_DIR: &str = "FFmpeg_build";

/// The build manifest path, relative to a target-specific configuration directory.
const MANIFEST_FILE: &str = "cinrs_manifest.toml";

const USAGE: &str = "\
Usage: cargo xtask <task>

Tasks:
  ffmpeg-manifest  Build a minimal FFmpeg configuration and write the build manifest
                   and generated configuration files to the directory for this
                   machine's target (mini-ffmpeg-sys/FFmpeg_build/<triple>)
  ffmpeg-license   Scan the build manifest's input files with licensecheck
                   See cargo xtask ffmpeg-license --help for options

Run these tasks when changing the FFmpeg version or configuration. The translation
units in the build manifest are translated to Rust by mini-ffmpeg-sys's build.rs;
there is no need to run a separate task for translation.";

/// The workspace root.
fn workspace_root() -> Result<&'static Path> {
    // The workspace root is one directory above the xtask crate.
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .ok_or_else(|| "cannot find the workspace root".into())
}

/// The `mini-ffmpeg-sys` crate directory, where task results are written.
fn sys_crate_dir() -> Result<PathBuf> {
    Ok(workspace_root()?.join("mini-ffmpeg-sys"))
}

/// Return the available target triples in alphabetical order.
///
/// These are the names of directories directly under `FFmpeg_build/`, used to show
/// available choices in error messages.
fn available_targets() -> Result<Vec<String>> {
    let mut targets = Vec::new();

    for entry in std::fs::read_dir(sys_crate_dir()?.join(BUILD_CONFIG_DIR))? {
        let entry = entry?;

        if entry.file_type()?.is_dir() {
            targets.push(entry.file_name().to_string_lossy().into_owned());
        }
    }

    targets.sort();

    Ok(targets)
}

fn main() -> ExitCode {
    let mut args = env::args().skip(1);
    let task = args.next();

    let args: Vec<String> = args.collect();

    if task.as_deref() != Some("ffmpeg-license") && !args.is_empty() {
        eprintln!("error: unexpected arguments: {}\n\n{USAGE}", args.join(" "));
        return ExitCode::FAILURE;
    }

    let result = match task.as_deref() {
        Some("ffmpeg-license") => ffmpeg_license::run(&args),
        Some("ffmpeg-manifest") => ffmpeg_manifest::run(),

        Some("help" | "--help" | "-h") | None => {
            println!("{USAGE}");
            return ExitCode::SUCCESS;
        }

        Some(other) => Err(format!("unknown task: {other}\n\n{USAGE}").into()),
    };

    match result {
        Ok(()) => ExitCode::SUCCESS,
        Err(error) => {
            eprintln!("error: {error}");
            ExitCode::FAILURE
        }
    }
}
