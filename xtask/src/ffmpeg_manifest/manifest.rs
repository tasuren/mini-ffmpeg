//! Data and serialization for the build manifest (`cinrs_manifest.toml`).

use std::{fmt::Write as _, path::Path};

use super::{
    FFMPEG_DIR,
    source_tree::{Location, SourceTree},
};
use crate::Result;

/// Information extracted from the FFmpeg build results for translation with cinrs.
///
/// All paths are relative and use `/` separators. Absolute paths would make the
/// contents depend on the generating machine, causing differences in committed
/// files each time they are regenerated.
#[derive(Debug)]
pub struct Manifest {
    /// The `FFMPEG_VERSION` value in `libavutil/ffversion.h`.
    pub ffmpeg_version: String,

    /// The generated files directory, relative to `mini-ffmpeg-sys`, in the form
    /// `FFmpeg_build/<triple>`. The build manifest itself is also stored here.
    pub generated_dir: String,

    /// Arguments passed to `configure`.
    pub configure_args: Vec<String>,

    /// The target triple for this configuration, matching its directory under `FFmpeg_build/`.
    ///
    /// `config.h` depends on the generating environment, so record its target. Generation
    /// runs on the target machine, matching the target of the compiler used by
    /// `configure` (the architecture is checked before writing).
    pub triple: String,

    /// The C standard (the value of `-std=`).
    pub c_standard: String,

    /// Macro definitions shared by all translation units (the values of `-D`).
    pub defines: Vec<String>,

    /// Include directories shared by all translation units, in search order.
    pub include_dirs: Vec<IncludeDir>,

    /// Compiled `.c` files, relative to the FFmpeg source tree.
    pub translation_units: Vec<String>,

    /// Sources included by translation units rather than compiled separately, such as
    /// `.c` templates. Paths are relative to the FFmpeg source tree.
    pub included_sources: Vec<String>,

    /// Headers included by translation units, relative to the FFmpeg source tree.
    pub headers: Vec<String>,

    /// Files generated by `configure` and `make` that translation units include.
    /// Paths are relative to the build directory; files are copied to the same paths
    /// under [`Manifest::generated_dir`].
    pub generated: Vec<String>,

    /// Headers included by translation units that FFmpeg installs as its public API.
    /// This is a subset of `headers` and `generated`, stored as `#include` names
    /// (such as `libavutil/avutil.h`).
    ///
    /// These headers provide the declarations and types exposed to library consumers.
    pub public_headers: Vec<String>,
}

/// The base directory for an include directory path.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum IncludeRoot {
    /// The directory holding files generated by `configure` and `make` ([`Manifest::generated_dir`]).
    Generated,

    /// The FFmpeg source tree root (`FFmpeg/`).
    Ffmpeg,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct IncludeDir {
    pub root: IncludeRoot,

    /// The path relative to its base directory; `.` denotes the base itself.
    pub path: String,
}

impl IncludeDir {
    /// Split a compile command's `-I` value into a base directory and relative path.
    ///
    /// FFmpeg runs `make` in the build directory and refers to the source tree through
    /// a `src` symlink or an absolute path.
    ///
    /// - Relative paths such as `.` are based in the build directory.
    /// - Paths recognized by `tree` as source tree paths are based in the FFmpeg source tree.
    ///
    /// Reject other absolute paths: they reference machine-specific directories and
    /// cannot be reproduced in other environments.
    pub fn classify(raw: &str, tree: &SourceTree) -> Result<Self> {
        match tree.classify(raw) {
            Location::Tree(path) => Ok(Self::new(IncludeRoot::Ffmpeg, path)),
            Location::Generated(path) => Ok(Self::new(IncludeRoot::Generated, path)),
            Location::External => Err(format!(
                "include directories outside the FFmpeg source tree are unsupported: {raw}"
            )
            .into()),
        }
    }

    /// Make the path relative to the `mini-ffmpeg-sys` root. `generated_dir` is
    /// [`Manifest::generated_dir`].
    ///
    /// cinrs resolves relative paths in `#pragma cinrs include_path` from the crate
    /// root. Both base directories are inside the crate, so this form can be used
    /// directly in the translation source.
    pub fn crate_relative(&self, generated_dir: &str) -> String {
        let root = match self.root {
            IncludeRoot::Generated => generated_dir,
            IncludeRoot::Ffmpeg => FFMPEG_DIR,
        };

        if self.path == "." {
            root.to_owned()
        } else {
            format!("{root}/{}", self.path)
        }
    }

    fn new(root: IncludeRoot, path: String) -> Self {
        Self {
            root,
            path: if path.is_empty() {
                ".".to_owned()
            } else {
                path
            },
        }
    }
}

/// Convert a path to a `/`-separated string, removing `.` components and trailing separators.
pub fn to_slash_path(path: &Path) -> String {
    path.components()
        .filter(|component| !matches!(component, std::path::Component::CurDir))
        .map(|component| component.as_os_str().to_string_lossy())
        .collect::<Vec<_>>()
        .join("/")
}

impl Manifest {
    /// Serialize as TOML.
    ///
    /// Write one array element per line so differences in committed generated files
    /// can be reviewed per element when regenerated.
    pub fn to_toml(&self) -> String {
        let mut out = String::new();

        out.push_str(
            "# Generated by `cargo xtask ffmpeg-manifest`. Do not edit manually.\n\
             # To change the configuration, update CONFIGURE_ARGS in xtask and regenerate.\n",
        );

        out.push_str("\n[ffmpeg]\n");
        write_string(&mut out, "version", &self.ffmpeg_version);
        write_array(&mut out, "configure_args", &self.configure_args);

        out.push_str(
            "\n# The target of this configuration. Files in the same directory were generated\n\
             # on a machine for this target. The build script checks that this matches\n\
             # the build target (`TARGET`).\n[target]\n",
        );
        write_string(&mut out, "triple", &self.triple);

        out.push_str("\n# Compile options shared by all translation units.\n[compile]\n");
        write_string(&mut out, "std", &self.c_standard);
        write_array(&mut out, "defines", &self.defines);

        let include_dirs: Vec<String> = self
            .include_dirs
            .iter()
            .map(|dir| dir.crate_relative(&self.generated_dir))
            .collect();

        out.push_str(
            "\n# In search order, relative to the `mini-ffmpeg-sys` root; usable directly in\n\
             # `#pragma cinrs include_path`.\n",
        );
        write_array(&mut out, "include_dirs", &include_dirs);

        out.push_str("\n[sources]\n");

        out.push_str("# Compiled `.c` files, relative to the FFmpeg source tree.\n");
        write_array(&mut out, "translation_units", &self.translation_units);

        out.push_str(
            "\n# Sources included by translation units rather than compiled separately.\n",
        );
        write_array(&mut out, "included_sources", &self.included_sources);

        out.push_str(
            "\n# Headers included by translation units, relative to the FFmpeg source tree.\n",
        );
        write_array(&mut out, "headers", &self.headers);

        out.push_str(
            "\n# Files generated by `configure` and `make` that translation units include.\n\
             # Paths are relative to the directory containing this file.\n",
        );
        write_array(&mut out, "generated", &self.generated);

        out.push_str(
            "\n# Headers from `headers` and `generated` above that FFmpeg installs as its public API.\n\
             # Names are used in `#include` and resolved through the include directories.\n",
        );
        write_array(&mut out, "public_headers", &self.public_headers);

        out
    }
}

fn write_string(out: &mut String, key: &str, value: &str) {
    let _ = writeln!(out, "{key} = {}", toml_string(value));
}

fn write_array(out: &mut String, key: &str, values: &[String]) {
    let _ = writeln!(out, "{key} = [");

    for value in values {
        let _ = writeln!(out, "    {},", toml_string(value));
    }

    out.push_str("]\n");
}

/// Serialize as a TOML basic string (a double-quoted string).
fn toml_string(value: &str) -> String {
    let mut out = String::with_capacity(value.len() + 2);
    out.push('"');

    for character in value.chars() {
        match character {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),

            // The remaining control characters cannot appear literally in TOML basic strings.
            character if character.is_control() => {
                let _ = write!(out, "\\u{:04X}", character as u32);
            }

            character => out.push(character),
        }
    }

    out.push('"');
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    fn tree() -> SourceTree {
        SourceTree::new(&["src", "/work/FFmpeg"], &["/work/build"])
    }

    fn classify(raw: &str) -> IncludeDir {
        IncludeDir::classify(raw, &tree()).unwrap()
    }

    fn dir(root: IncludeRoot, path: &str) -> IncludeDir {
        IncludeDir {
            root,
            path: path.to_owned(),
        }
    }

    /// `-I.` points to the build directory, which holds generated files such as `config.h`.
    #[test]
    fn classifies_build_directory() {
        assert_eq!(classify("."), dir(IncludeRoot::Generated, "."));
        assert_eq!(
            classify("libavcodec"),
            dir(IncludeRoot::Generated, "libavcodec")
        );
    }

    /// FFmpeg refers to its source tree through a `src` symlink, passed as `-Isrc/`
    /// with a trailing slash. Parse that form as well.
    #[test]
    fn classifies_src_symlink_as_ffmpeg_tree() {
        assert_eq!(classify("src/"), dir(IncludeRoot::Ffmpeg, "."));
        assert_eq!(classify("src"), dir(IncludeRoot::Ffmpeg, "."));
        assert_eq!(
            classify("src/compat/stdbit"),
            dir(IncludeRoot::Ffmpeg, "compat/stdbit")
        );
    }

    /// Directories under `compat` use absolute paths. Convert them to source-tree-relative
    /// paths so the build manifest does not retain the generating machine's paths.
    #[test]
    fn classifies_absolute_path_inside_ffmpeg_tree() {
        assert_eq!(
            classify("/work/FFmpeg/compat/stdbit"),
            dir(IncludeRoot::Ffmpeg, "compat/stdbit"),
        );
    }

    /// Do not mistake another directory with a `src` prefix (`srcfoo`) for the `src`
    /// symlink.
    #[test]
    fn does_not_treat_src_prefixed_name_as_symlink() {
        assert_eq!(classify("srcfoo"), dir(IncludeRoot::Generated, "srcfoo"));
    }

    #[test]
    fn rejects_absolute_path_outside_ffmpeg_tree() {
        assert!(IncludeDir::classify("/opt/homebrew/include", &tree()).is_err());
    }

    /// Paths written to the build manifest are used directly in
    /// `#pragma cinrs include_path` in the translation source. Do not append redundant
    /// components such as `FFmpeg/.` when the path is the base directory itself (`.`).
    #[test]
    fn renders_include_dir_relative_to_crate_root() {
        let generated = "FFmpeg_build/aarch64-apple-darwin";

        assert_eq!(classify(".").crate_relative(generated), generated);
        assert_eq!(classify("src/").crate_relative(generated), "FFmpeg");
        assert_eq!(
            classify("/work/FFmpeg/compat/stdbit").crate_relative(generated),
            "FFmpeg/compat/stdbit",
        );
    }

    #[test]
    fn escapes_toml_strings() {
        assert_eq!(toml_string(r#"a"b\c"#), r#""a\"b\\c""#);
        assert_eq!(toml_string("a\tb\u{1}"), "\"a\\tb\\u0001\"");
    }
}
