//! Build a minimal FFmpeg configuration and write its contents to a build manifest.
//!
//! Reading FFmpeg's `Makefile` alone does not determine which `.c` files are compiled:
//! component dependencies live in `configure`, and enabling one component can enable
//! others implicitly. Run `configure` and `make` and extract the configuration from
//! their results instead.
//!
//! 1. Run `configure` in a build directory outside the source tree.
//! 2. Use `make -n V=1` to obtain the compile commands that would run, revealing the
//!    translation units, include directories, and macro definitions.
//! 3. Build with `make`. The dependency files (`.d`) the compiler writes for each
//!    translation unit identify the included files.
//! 4. Use `make -n install-headers` to obtain headers FFmpeg installs as its public
//!    API. Keep those included by translation units as public headers.
//! 5. Write the build manifest to `cinrs_manifest.toml` and copy the required files
//!    generated by `configure` and `make` into the same `FFmpeg_build/<triple>/`.
//!
//! The output location is determined by `rustc`'s host triple on the machine running
//! the task ([`triple`]). Since `configure` probes that machine, configurations for
//! other targets must be generated on machines for those targets.
//!
//! All input and output locations are inside `mini-ffmpeg-sys`. The FFmpeg source
//! tree is the `FFmpeg/` submodule. Keeping everything inside the crate directory
//! allows it to be packaged for crates.io without a tool copying files into place.
//!
//! The results are committed, so consumer builds need neither `configure` nor `make`.

