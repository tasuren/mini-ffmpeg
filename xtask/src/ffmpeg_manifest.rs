/// Arguments passed to `configure`, the single source of truth for the FFmpeg configuration to translate.
const CONFIGURE_ARGS: &[&str] = &[
    // Disable all components, libraries, programs, and documentation. Only libavutil
    // remains enabled; add the required libraries and components below.
    "--disable-all",
    // Do not automatically enable external libraries installed on the machine.
    //
    // Without this option, `config.h` still contains `CONFIG_AUTODETECT 0`, but that
    // only writes an unset value as 0; autodetection still runs. On macOS, it enables
    // VideoToolbox, zlib, and even Homebrew libraries, increasing the compiled sources
    // and making `config.h` depend on the generating machine.
    "--disable-autodetect",
    "--enable-avcodec",
    "--enable-avformat",
    // Disable assembly optimizations because cinrs can only translate C.
    // `--disable-asm` alone leaves inline assembly in C code enabled
    // (`HAVE_INLINE_ASM` becomes 1), so specify both options.
    "--disable-asm",
    "--disable-inline-asm",
    "--disable-network",
    // Disable threads only for the initial spike to make problems easier to isolate.
    // This turns FFmpeg's internal mutexes into no-ops, so the option must be removed
    // for a configuration used as a library.
    "--disable-pthreads",
    // The spike only needs components for WAV-to-WAV `-c copy`.
    "--enable-demuxer=wav",
    "--enable-muxer=wav",
    "--enable-protocol=file,pipe",
    // Use MSVC's `cl.exe`; otherwise, `configure` looks for gcc.
    // This selects a compiler rather than an OS, so require both `windows` and `msvc`.
    // Since `configure_args` is recorded in the build manifest, Windows manifests
    // differ from those for other operating systems.
    #[cfg(all(windows, target_env = "msvc"))]
    "--toolchain=msvc",
];

/// The FFmpeg source tree (a submodule), relative to `mini-ffmpeg-sys`.
const FFMPEG_DIR: &str = "FFmpeg";

/// Locations read and written by this task.
struct Paths {
    /// The FFmpeg source tree as an absolute path with symlinks resolved.
    ffmpeg_src: PathBuf,

    /// The directory outside the source tree where `configure` and `make` run.
    build_dir: PathBuf,

    /// The `rustc` host triple used to name the configuration.
    triple: String,

    /// The output directory (`mini-ffmpeg-sys/FFmpeg_build/<triple>`).
    ///
    /// This task owns the entire directory and recreates it on every run. Manually
    /// added files are deleted. Directories for other triples are left untouched.
    output_dir: PathBuf,
}

impl Paths {
    fn locate() -> Result<Self> {
        let sys_crate = sys_crate_dir()?;
        let ffmpeg_src = sys_crate.join(FFMPEG_DIR);

        if !ffmpeg_src.join("configure").is_file() {
            return Err(format!(
                "FFmpeg configure was not found in {}.\n\
                 Fetch the submodule: git submodule update --init",
                ffmpeg_src.display(),
            )
            .into());
        }

        let triple = triple::host_triple()?;

        Ok(Self {
            // Pass an absolute path to `configure`. Include directories in compile commands
            // then use the same absolute prefix, allowing them to be identified and converted
            // to source-tree-relative paths later.
            ffmpeg_src: ffmpeg_src.canonicalize()?,

            // `/target` is gitignored, so it can hold intermediate build files.
            build_dir: workspace_root()?.join("target/xtask/ffmpeg-build"),

            output_dir: sys_crate.join(BUILD_CONFIG_DIR).join(&triple),
            triple,
        })
    }
}

pub fn run() -> Result<()> {
    let paths = Paths::locate()?;

    // Old `.o` or `.d` files could add files not compiled in this configuration to the
    // build manifest. Always start with an empty build directory.
    if paths.build_dir.exists() {
        fs::remove_dir_all(&paths.build_dir)?;
    }

    fs::create_dir_all(&paths.build_dir)?;

    println!("Running configure...");
    configure(&paths)?;

    let tree = SourceTree::read(&paths.build_dir, &paths.ffmpeg_src)?;
    let target_arch = detect_target_arch(&paths)?;

    // Check that the triple name matches the contents before saving the configuration.
    triple::check_arch_matches(&paths.triple, &target_arch)?;

    // After building, `make -n` reports nothing to do and omits the commands.
    // Always collect them before the build.
    let commands = dry_run_compile_commands(&paths)?;

    println!("Running make ({} translation units)...", commands.len());
    build(&paths)?;

    let installed_headers = dry_run_installed_headers(&paths)?;

    let manifest = collect(&paths, &tree, &commands, &installed_headers)?;
    write_outputs(&paths, &manifest)?;

    println!(
        "Wrote output to {}.\n  \
         FFmpeg {}\n  \
         {} translation units, {} include-only sources, {} headers, {} generated files\n  \
         {} public headers (those included by translation units, out of {} installed headers)",
        paths.output_dir.display(),
        manifest.ffmpeg_version,
        manifest.translation_units.len(),
        manifest.included_sources.len(),
        manifest.headers.len(),
        manifest.generated.len(),
        manifest.public_headers.len(),
        installed_headers.len(),
    );

    Ok(())
}

fn configure(paths: &Paths) -> Result<()> {
    // Windows cannot execute shell scripts directly, so invoke them through bash.
    // Use bash on other operating systems too, avoiding reliance on executable bits.
    // Windows paths from `canonicalize` have a `\\?\` prefix that bash cannot read;
    // convert them with `native_path`.
    let script = source_tree::native_path(&paths.ffmpeg_src.join("configure"));

    let mut command = Command::new("bash");
    command.arg(script);
    command.args(CONFIGURE_ARGS).current_dir(&paths.build_dir);

    run_logged(command, &paths.build_dir.join("xtask-configure.log")).map_err(|error| {
        // Details of a `configure` failure are in its own log.
        format!(
            "{error}\nDetails: {}",
            paths.build_dir.join("ffbuild/config.log").display(),
        )
        .into()
    })
}

/// Determine the target CPU architecture of the compiler used by `configure`.
/// See [`target_arch`] for the method.
fn detect_target_arch(paths: &Paths) -> Result<String> {
    fs::write(
        paths.build_dir.join(target_arch::PROBE_SOURCE),
        target_arch::PROBE,
    )?;

    let mut command = Command::new("make");
    command
        .args(["V=1", target_arch::PROBE_OUTPUT])
        .current_dir(&paths.build_dir);

    run_logged(command, &paths.build_dir.join("xtask-target-arch.log"))?;

    let output_path = paths.build_dir.join(target_arch::PROBE_OUTPUT);
    let output = fs::read_to_string(&output_path)
        .map_err(|error| format!("cannot read {}: {error}", output_path.display()))?;

    target_arch::parse_preprocessed(&output)
}

/// Run `make -n V=1` and collect C compile commands from its output.
///
/// `-n` prints commands without executing them. `V=1` is an FFmpeg Makefile option;
/// without it, output is abbreviated to forms such as `CC libavutil/log.o`.
fn dry_run_compile_commands(paths: &Paths) -> Result<Vec<CompileCommand>> {
    let output = Command::new("make")
        .args(["-n", "V=1"])
        .current_dir(&paths.build_dir)
        .output()
        .map_err(|error| format!("cannot run make: {error}"))?;

    if !output.status.success() {
        return Err(format!(
            "make -n V=1 failed ({})\n{}",
            output.status,
            String::from_utf8_lossy(&output.stderr),
        )
        .into());
    }

    let stdout = String::from_utf8(output.stdout)?;
    let mut commands = Vec::new();

    for line in stdout.lines() {
        if let Some(command) = compile_command::parse_line(line)? {
            commands.push(command);
        }
    }

    if commands.is_empty() {
        return Err("make -n V=1 output contains no compile commands".into());
    }

    Ok(commands)
}

/// Run `make -n install-headers` and collect installed headers from its output.
///
/// `-n` only prints commands, so nothing is written to the installation destination.
/// The destination directory is only used to read the library name.
fn dry_run_installed_headers(paths: &Paths) -> Result<Vec<InstalledHeader>> {
    let output = Command::new("make")
        .args(["-n", "install-headers"])
        .current_dir(&paths.build_dir)
        .output()
        .map_err(|error| format!("cannot run make: {error}"))?;

    if !output.status.success() {
        return Err(format!(
            "make -n install-headers failed ({})\n{}",
            output.status,
            String::from_utf8_lossy(&output.stderr),
        )
        .into());
    }

    let stdout = String::from_utf8(output.stdout)?;
    let mut headers = Vec::new();

    for line in stdout.lines() {
        headers.extend(install_headers::parse_line(line)?);
    }

    if headers.is_empty() {
        return Err(
            "make -n install-headers output contains no header installation commands".into(),
        );
    }

    Ok(headers)
}

fn build(paths: &Paths) -> Result<()> {
    let jobs = thread::available_parallelism().map_or(1, usize::from);

    let mut command = Command::new("make");
    command
        .arg(format!("-j{jobs}"))
        .current_dir(&paths.build_dir);

    run_logged(command, &paths.build_dir.join("xtask-make.log"))
}

/// Run a command and write stdout and stderr to a log file.
///
/// `configure` and `make` produce too much output for the terminal. On failure,
/// include the log file location in the error.
fn run_logged(mut command: Command, log_path: &Path) -> Result<()> {
    let log = File::create(log_path)?;

    let status = command
        .stdout(log.try_clone()?)
        .stderr(log)
        .status()
        .map_err(|error| {
            format!(
                "cannot run {}: {error}",
                command.get_program().to_string_lossy(),
            )
        })?;

    if !status.success() {
        return Err(format!(
            "{} failed ({status})\nLog: {}",
            command.get_program().to_string_lossy(),
            log_path.display(),
        )
        .into());
    }

    Ok(())
}

/// Construct the build manifest from build results and compile commands.
fn collect(
    paths: &Paths,
    tree: &SourceTree,
    commands: &[CompileCommand],
    installed_headers: &[InstalledHeader],
) -> Result<Manifest> {
    check_built_objects(paths, commands)?;

    let flags = common_flags(commands)?;

    let mut translation_units = BTreeSet::new();
    let mut tree_dependencies = BTreeSet::new();
    let mut generated = BTreeSet::new();

    for command in commands {
        let Location::Tree(source) = tree.classify(&command.source) else {
            // Some configurations compile `.c` files generated during the build to embed
            // binaries as C arrays. These use rules with `RUN_BIN2C` in `ffbuild/common.mak`:
            // CUDA filters (`*.ptx.c`), Vulkan shaders (`*.spv.c`), Metal (`*.metallib.c`),
            // and fftools resources (`*.html.c` and `*.css.c`). None are enabled in the current
            // configuration; decide how to handle them when they are needed.
            //
            // Hardcoded tables (`--enable-hardcoded-tables`) do not reach this case. They
            // produce headers such as `libavcodec/pcm_tables.h`, collected below when reading
            // dependencies as generated files included by translation units.
            return Err(format!(
                "compiling sources outside the FFmpeg source tree is unsupported: {}",
                command.source,
            )
            .into());
        };

        translation_units.insert(source);

        let depfile_path = paths.build_dir.join(&command.object).with_extension("d");
        let depfile = fs::read_to_string(&depfile_path)
            .map_err(|error| format!("cannot read {}: {error}", depfile_path.display()))?;

        for dependency in depfile::parse_dependencies(&depfile)? {
            match tree.classify(&dependency) {
                Location::Tree(path) => tree_dependencies.insert(path),
                Location::Generated(path) => generated.insert(path),
                Location::External => false,
            };
        }
    }

    // Exclude translation units themselves from source tree dependencies, then
    // separate headers from other files, such as templates included by other `.c` files.
    let (headers, included_sources): (Vec<_>, Vec<_>) = tree_dependencies
        .into_iter()
        .filter(|path| !translation_units.contains(path))
        .partition(|path| path.ends_with(".h"));

    let include_dirs = flags
        .include_dirs
        .iter()
        .map(|raw| IncludeDir::classify(raw, tree))
        .collect::<Result<Vec<_>>>()?;

    let generated: Vec<String> = generated.into_iter().collect();

    let public_headers =
        install_headers::select_public_headers(installed_headers, tree, &headers, &generated)?;

    Ok(Manifest {
        ffmpeg_version: read_ffmpeg_version(paths)?,
        generated_dir: format!("{BUILD_CONFIG_DIR}/{}", paths.triple),
        configure_args: CONFIGURE_ARGS.iter().map(|arg| (*arg).to_owned()).collect(),
        triple: paths.triple.clone(),
        c_standard: flags.std.ok_or("compile command is missing -std=")?,
        defines: flags.defines,
        include_dirs,
        translation_units: translation_units.into_iter().collect(),
        included_sources,
        headers,
        generated,
        public_headers,
    })
}

/// Check that all translation units use the same flags and return that common set.
///
/// The build manifest stores only one set of flags. Discarding per-unit differences
/// would translate code that differs from the original build. If differences appear,
/// the manifest must be changed to store flags per translation unit.
///
/// This also detects host programs run during the build. For example,
/// `--enable-hardcoded-tables` compiles table generators (such as
/// `libavcodec/pcm_tablegen.c`) with commands shaped like those for library
/// translation units. Their command form does not distinguish them, but their flags
/// differ (they lack `-DHAVE_AV_CONFIG_H`), so this check rejects them before they
/// enter the build manifest as translation units.
fn common_flags(commands: &[CompileCommand]) -> Result<CompileFlags> {
    let first = &commands[0];

    if let Some(different) = commands.iter().find(|command| command.flags != first.flags) {
        return Err(format!(
            "compile flags differ between translation units.\n\
             {}: {:?}\n\
             {}: {:?}",
            first.source, first.flags, different.source, different.flags,
        )
        .into());
    }

    Ok(first.flags.clone())
}

/// Check that translation units read from `make -n` match the built object files.
///
/// Compile command parsing relies on assumptions about command format. This check
/// prevents silently writing an incomplete build manifest if those assumptions fail
/// and translation units are missed.
fn check_built_objects(paths: &Paths, commands: &[CompileCommand]) -> Result<()> {
    let expected: BTreeSet<String> = commands
        .iter()
        .map(|command| to_slash_path(Path::new(&command.object)))
        .collect();

    let mut built = BTreeSet::new();
    find_objects(&paths.build_dir, &paths.build_dir, &mut built)?;

    if expected == built {
        return Ok(());
    }

    let missing: Vec<_> = expected.difference(&built).collect();
    let unexpected: Vec<_> = built.difference(&expected).collect();

    Err(format!(
        "compile commands do not match the build results.\n\
         commands with no object file: {missing:?}\n\
         object files with no command: {unexpected:?}",
    )
    .into())
}

/// Collect `.o` files under `dir` as paths relative to `root`.
fn find_objects(root: &Path, dir: &Path, objects: &mut BTreeSet<String>) -> Result<()> {
    for entry in fs::read_dir(dir)? {
        let entry = entry?;
        let path = entry.path();

        // `is_dir` on `DirEntry::file_type` does not follow symlinks. Rely on this because
        // environments supporting symlinks have a `src` link to the FFmpeg source tree in
        // the build directory; following it would traverse the entire source tree.
        let file_type = entry.file_type()?;

        if file_type.is_dir() {
            find_objects(root, &path, objects)?;
        } else if file_type.is_file() && path.extension().is_some_and(|ext| ext == "o") {
            let relative = path.strip_prefix(root).expect("traversal is under root");

            objects.insert(to_slash_path(relative));
        }
    }

    Ok(())
}

/// Read the FFmpeg version from `libavutil/ffversion.h` generated by `make`.
///
/// FFmpeg determines this version from `git describe` and similar sources during
/// the build, so it matches the version reported by the code being translated.
fn read_ffmpeg_version(paths: &Paths) -> Result<String> {
    let path = paths.build_dir.join("libavutil/ffversion.h");
    let content = fs::read_to_string(&path)
        .map_err(|error| format!("cannot read {}: {error}", path.display()))?;

    content
        .lines()
        .find_map(|line| {
            line.strip_prefix("#define FFMPEG_VERSION ")
                .map(|value| value.trim().trim_matches('"').to_owned())
        })
        .ok_or_else(|| format!("{} does not contain FFMPEG_VERSION", path.display()).into())
}

fn write_outputs(paths: &Paths, manifest: &Manifest) -> Result<()> {
    let output_dir = &paths.output_dir;

    // Configuration changes can leave generated files obsolete. Recreate the entire
    // directory owned by this task to avoid retaining old files.
    if output_dir.exists() {
        fs::remove_dir_all(output_dir)?;
    }

    fs::create_dir_all(output_dir)?;

    for generated in &manifest.generated {
        let destination = output_dir.join(generated);

        if let Some(parent) = destination.parent() {
            fs::create_dir_all(parent)?;
        }

        // Copy generated files without modification, preserving paths relative to the
        // build directory. Using this directory as an include directory then reproduces
        // `-I.` from the original build.
        fs::copy(paths.build_dir.join(generated), &destination)?;
    }

    fs::write(output_dir.join(MANIFEST_FILE), manifest.to_toml())?;

    Ok(())
}
